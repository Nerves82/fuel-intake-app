"""
Builds the app's copy of DCF form 201SF (Vermont Fuel Assistance Eligibility Review, rev 01/2024)
from reference/forms/ESD-Form-201SF.pdf:

  src/FuelIntake.UI/Printing/Form201SF/page1..3.png   the printed pages (no form fields), 220 dpi
  src/FuelIntake.Core/Forms/Form201SFLayout.g.cs      where each box/line is, in points from the top left

Run from the repo root when the state issues a new revision:  python3 reference/forms/make_201sf.py
Needs pypdf, Pillow and poppler's pdftoppm.
"""
import os, subprocess, tempfile
import pypdf
from PIL import Image

SRC = "reference/forms/ESD-Form-201SF.pdf"
PNG = "src/FuelIntake.UI/Printing/Form201SF"
CS = "src/FuelIntake.Core/Forms/Form201SFLayout.g.cs"
H = 792.0

def read_only(a):
    """Fixed text printed by the form itself, e.g. "(201SFREV in OnBase)" by the barcode: kept on the page image."""
    return int(a.get("/Ff", 0)) & 1 == 1 and a.get("/V") is not None

def widgets(reader):
    for pi, page in enumerate(reader.pages, 1):
        for a in page.get("/Annots") or []:
            a = a.get_object()
            if a.get("/Subtype") != "/Widget" or read_only(a):
                continue
            names, o = [], a
            while o is not None:
                if "/T" in o:
                    names.append(str(o["/T"]))
                o = o["/Parent"].get_object() if "/Parent" in o else None
            x1, y1, x2, y2 = (float(v) for v in a["/Rect"])
            ft = a.get("/FT") or (a["/Parent"].get_object().get("/FT") if "/Parent" in a else None)
            yield dict(page=pi, name=".".join(reversed(names)).replace("topmostSubform[0].", ""),
                       box=str(ft) == "/Btn", x=x1, y=H - y2, w=x2 - x1, h=y2 - y1)

def main():
    reader = pypdf.PdfReader(SRC)
    ws = list(widgets(reader))

    # --- page images without the fields
    w = pypdf.PdfWriter(clone_from=reader)
    for p in w.pages:
        if "/Annots" in p:
            keep = [x for x in p["/Annots"] if read_only(x.get_object())]
            if keep:
                p[pypdf.generic.NameObject("/Annots")] = pypdf.generic.ArrayObject(keep)
            else:
                del p["/Annots"]
    if "/AcroForm" in w._root_object:
        del w._root_object["/AcroForm"]
    os.makedirs(PNG, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        flat = os.path.join(tmp, "flat.pdf")
        w.write(flat)
        subprocess.run(["pdftoppm", "-r", "220", "-png", flat, os.path.join(tmp, "p")], check=True)
        for i in (1, 2, 3):
            im = Image.open(os.path.join(tmp, f"p-{i}.png")).convert("RGB")
            im = im.quantize(colors=32, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
            im.save(os.path.join(PNG, f"page{i}.png"), optimize=True)

    # --- layout: every widget by page and position (the field names in this PDF don't match their labels,
    #     so the C# side picks boxes by position, see Form201SF.cs)
    lines = []
    for f in sorted(ws, key=lambda f: (f["page"], round(f["y"]), f["x"])):
        lines.append(f'        new({f["page"]}, {f["x"]:.1f}, {f["y"]:.1f}, {f["w"]:.1f}, {f["h"]:.1f}, {str(f["box"]).lower()}, "{f["name"]}"),')
    os.makedirs(os.path.dirname(CS), exist_ok=True)
    with open(CS, "w", newline="\n") as out:
        out.write("// <auto-generated> by reference/forms/make_201sf.py from ESD-Form-201SF.pdf (rev 01/2024). Don't edit. </auto-generated>\n")
        out.write("namespace FuelIntake.Core.Forms;\n\n")
        out.write("public static partial class Form201SFLayout\n{\n")
        out.write("    /// <summary>Every fillable box on the state's PDF: page, left, top, width, height (points), checkbox, PDF field name.</summary>\n")
        out.write("    public static readonly IReadOnlyList<FormSpot> Spots =\n    [\n")
        out.write("\n".join(lines))
        out.write("\n    ];\n}\n")
    print(f"{len(ws)} spots")

if __name__ == "__main__":
    main()
